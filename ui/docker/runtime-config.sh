#!/bin/sh
set -eu

TARGET="${RUNTIME_CONFIG_PATH:-/usr/share/nginx/html/knowledge-provider/config.js}"
TEMPLATE=/etc/knowledge-provider/config.js.template
MARKER="/* generated by runtime-config.sh */"

if [ -d "$TARGET" ]; then
  echo "runtime-config: $TARGET is a directory" >&2
  exit 1
fi

if [ -f "$TARGET" ] && ! head -n 1 "$TARGET" | grep -qF "$MARKER"; then
  echo "runtime-config: keeping provided $TARGET"
  exit 0
fi

TMP="$(mktemp)"
echo "$MARKER" > "$TMP"
envsubst '${API_BASE} ${AUTH_ENABLED} ${KEYCLOAK_URL} ${KEYCLOAK_REALM} ${KEYCLOAK_CLIENT_ID} ${KEYCLOAK_IDP_HINT} ${DOCUMENT_VALIDITY_ENABLED}' < "$TEMPLATE" >> "$TMP"
cat "$TMP" > "$TARGET"
rm -f "$TMP"
echo "runtime-config: wrote $TARGET"
